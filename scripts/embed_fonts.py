"""Embed licensed Geist variable fonts and their license; stdlib only."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
output=['/* Generated by scripts/embed_fonts.py. Do not edit. */']
for symbol,name in [('geist_regular','Geist-Variable.ttf'),('geist_italic','Geist-Italic-Variable.ttf')]:
    data=(root/'assets/fonts'/name).read_bytes()
    output.append('static const unsigned char '+symbol+'[] = {')
    output.extend(','.join(str(v) for v in data[i:i+24])+',' for i in range(0,len(data),24))
    output.append('};')
license=(root/'assets/fonts/OFL.txt').read_text()
output.append('static const char geist_license[] = {'+','.join(str(v) for v in license.encode())+',0};')
(root/'assets/fonts/embedded.h').write_text('\n'.join(output)+'\n')
